export function computeMetricsFromData(orders: Order[], products: Product[]): DashboardMetrics {
  const validOrders = orders.filter((o) => o.status !== 'cancelled' && o.status !== 'returned');
  const totalSales = validOrders.reduce((sum, o) => sum + o.totalAmount, 0);
  const totalOrders = orders.length;
  const pendingOrders = orders.filter((o) => o.status === 'pending' || o.status === 'processing').length;
  const fulfilledOrders = orders.filter((o) => o.status === 'fulfilled').length;
  const cancelledOrders = orders.filter((o) => o.status === 'cancelled').length;
  const totalProducts = products.length;
  const lowStockCount = products.filter((p) => p.stock <= p.lowStockThreshold).length;
  const returnsAwaitingAction = 1;
  const codPendingAmount = orders
    .filter((o) => o.paymentMethod === 'COD' && o.paymentStatus === 'cod_pending')
    .reduce((sum, o) => sum + o.totalAmount, 0);
  const codReconciledAmount = orders
    .filter((o) => o.paymentMethod === 'COD' && o.paymentStatus === 'paid')
    .reduce((sum, o) => sum + o.totalAmount, 0);

  return {
    totalSales,
    totalOrders,
    pendingOrders,
    fulfilledOrders,
    cancelledOrders,
    totalProducts,
    lowStockCount,
    returnsAwaitingAction,
    codPendingAmount,
    codReconciledAmount,
  };
}
